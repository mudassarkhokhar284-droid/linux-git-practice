#!/bin/bash
echo "======================================================="
echo "-------------SYSTEM RESOURCES DASHBOARD----------------"
echo "======================================================="

echo -e "\n ------ DISK USAGE -------"
df -h | awk 'NR==1 || NR==2 {print $1 ,$2, $3, $4, $5}'
echo -e "\n ------ RAM MEMORY USAGE ----------"
free -h
echo -e "\n ------- SYSTEM UPDATE AND LOAD -------"
uptime
